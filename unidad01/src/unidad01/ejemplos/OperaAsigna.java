package unidad01.ejemplos;

public class OperaAsigna {

	public static void main(String[] args) {

		// +=
		int numero = 20;

		numero = numero + 30;
		numero += 30;

		// -=
		int numero2 = 65;

		numero2 = numero2 - 35;
		numero2 -= 35;

		// *=
		int numero3 = 15;

		numero3 = numero3 * 3;
		numero3 *= 3;

		// /=
		int numero4 = 40;

		numero4 = numero4 / 2;
		numero4 /= 2;

		// %=
		int numero5 = 40;

		numero5 = numero5 % 2;
		numero5 %= 2;

	}

}
